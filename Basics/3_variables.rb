# Variable : A variable is a named storage location used to store data that can be accessed and changed in a program.

#Creating variables

name = "Krish"
age = 18
gpa = 8.60

#Execution of variable 
puts name 
puts age 
puts gpa 


# String interpolation : You can insert variables inside strings using #{}

puts "My name is #{name}"
puts "I am #{age} years old"


#Example
language = "ruby"
goal = "SDE"

puts "Hey there! #{name} here."
puts "I am #{age}, years old"
puts "I am learning #{language} programming language."
puts "GPA : #{gpa}"
puts "My goal is to become a #{goal}"


